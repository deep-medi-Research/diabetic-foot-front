    [Fact]
    public void FixedMatchesPrintf()
    {
        foreach (var (value, digits, expected) in Cases)
        {
            Assert.True(CFormat.Fixed(value, digits) == expected, $"{value:R} with {digits} digits: expected {expected}, got {CFormat.Fixed(value, digits)}");
        }
    }

    [Fact]
    public void ZeroPadCountsSignInWidth()
    {
        Assert.Equal("07", CFormat.ZeroPad(7, 2));
        Assert.Equal("2026", CFormat.ZeroPad(2026, 4));
        Assert.Equal("123", CFormat.ZeroPad(123, 2));
        Assert.Equal("-01", CFormat.ZeroPad(-1, 3));
        Assert.Equal("-0001", CFormat.ZeroPad(-1, 5));
        Assert.Equal("0000", CFormat.ZeroPad(0, 4));
    }

    [Fact]
    public void HexUsesRequestedCase()
    {
        Assert.Equal("0001", CFormat.HexLower(1, 4));
        Assert.Equal("9a", CFormat.HexLower(0x9a, 2));
        Assert.Equal("0403", CFormat.HexUpper(0x0403, 4));
        Assert.Equal("A5", CFormat.HexUpper(0xa5, 2));
    }
