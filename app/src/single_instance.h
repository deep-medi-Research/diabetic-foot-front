#ifndef HWLAB_APP_SINGLE_INSTANCE_H_
#define HWLAB_APP_SINGLE_INSTANCE_H_

// 장치(카메라, 열화상, 직렬 포트)를 여는 실행이 하나만 돌게 합니다.
//
// 두 실행이 같은 장치를 열면 한쪽이 실패하거나 드라이버 호출에서 서로 기다리다 멈추는 일이 있었습니다(2026-10-27 노트북,
// 6초 간격으로 켠 v0.1.8 두 개가 종료 중 멈춤). 개발 빌드와 릴리즈도 같은 이름을 써서 함께 돌지 않습니다.
// 결과 창만 띄우는 실행(--result)과 가짜 장치 실행(--fake)은 장치를 열지 않으므로 부르지 않습니다.

enum class InstanceClaim {
  kAlone,       // 다른 실행이 없거나, 멈춘 실행을 끝내고 장치를 넘겨받음. 이어서 시작합니다
  kShownOther,  // 창이 있는 다른 실행을 앞으로 가져옴. 이 실행은 끝냅니다
  kStopped,     // 멈춘 실행을 끝내지 않기로 했거나 끝나지 않음. 이 실행은 끝냅니다
};

/**
 * 장치를 쓸 권리를 얻습니다. 이미 다른 실행이 있으면 사람에게 묻거나 그 창을 보입니다.
 *
 * 다른 실행에 보이는 창이 있으면 그 창을 앞으로 가져옵니다. 보이는 창이 없으면(창을 닫았는데 종료 중에 멈춘 실행)
 * 끝낼지 묻고, 예를 고르면 그 프로세스를 끝낸 뒤 최대 15초 기다려 장치를 넘겨받습니다.
 *
 * @return 이 실행을 이어서 시작할지(kAlone)
 * @note Windows가 아니면 늘 kAlone입니다. 얻은 권리는 프로세스가 끝날 때 Windows가 풉니다.
 */
InstanceClaim ClaimDevices();

#endif  // HWLAB_APP_SINGLE_INSTANCE_H_
